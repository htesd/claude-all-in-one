const dictionaries: Record<Lang, Record<I18nKey, string>> = { zh, en }

interface I18nContextValue {
  lang: Lang
  setLang: (lang: Lang) => void
  /** 取译文;可选 params 做 `{name}` 占位替换(如 `t('logs.page.total', { total: 12 })`)。 */
  t: (key: I18nKey, params?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function readInitialLang(): Lang {
  try {
    return localStorage.getItem(LANG_STORAGE_KEY) === 'en' ? 'en' : 'zh'
  } catch {
    return 'zh'
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readInitialLang)

  const setLang = useCallback((next: Lang) => {
    try {
      localStorage.setItem(LANG_STORAGE_KEY, next)
    } catch {
      /* ignore storage errors */
    }
    setLangState(next)
  }, [])

  const t = useCallback(
    (key: I18nKey, params?: Record<string, string | number>) => {
      let s = dictionaries[lang][key] ?? zh[key]
      if (params) {
        for (const [k, v] of Object.entries(params)) {
          s = s.split(`{${k}}`).join(String(v))
        }
      }
      return s
    },
    [lang],
  )

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext)
  if (!ctx) {
    throw new Error('useI18n must be used within an I18nProvider')
  }
  return ctx
}
